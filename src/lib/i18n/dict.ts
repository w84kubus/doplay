export const DICT: Record<Locale, Record<Key, string>> = { pl, en };

/** Podstawia {parametry}. Brak klucza → zwraca klucz, żeby brak tłumaczenia był widoczny. */
export function translate(locale: Locale, key: Key, params?: Params): string {
  const raw = DICT[locale]?.[key] ?? DICT.pl[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, p) => String(params[p] ?? m));
}
